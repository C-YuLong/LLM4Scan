"""Generate, execute and repair task-one dofiles with real acceptance evidence."""

import argparse
import json
import os
from pathlib import Path
import re
import signal
import time
import traceback
import urllib.request
from urllib.error import HTTPError

from scan_runner import run_scan, generated_script, record_change, publish_run, resolve_selectors
from acceptance import inspect_run
from model_contract import TASK1


def prepare_output(target):
    target.mkdir(parents=True, exist_ok=True)
    if any(target.iterdir()):
        raise ValueError("Output directory must be empty; previous runs are preserved")
    # Persist a truthful decision before the first network/tool operation.
    (target / "decision_log.json").write_text(json.dumps({
        "case_id": os.environ.get("CASE_ID", ""), "final_run": None,
        "summary": "Execution started; acceptance pending.",
        "tool_runs": [], "file_changes": [], "issue_resolutions": [],
    }, indent=2), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-input", "--input", required=True)
    parser.add_argument("-output", "--output", required=True)
    args = parser.parse_args()
    target = Path(args.output).resolve()
    # Check before entering the failure handler: never rewrite an old run.
    if target.exists() and any(target.iterdir()):
        raise ValueError("Output directory must be empty; previous runs are preserved")
    try:
        return execute(args)
    except Exception as exc:
        signal.setitimer(signal.ITIMER_REAL, 0)
        decision_path = target / "decision_log.json"
        if decision_path.exists():
            decision = json.loads(decision_path.read_text(encoding="utf-8"))
            decision.update({
                "task": "task2" if (Path(args.input) / "original.dofile").exists() else "task1",
                "final_run": None, "summary": "Execution failed before final acceptance.",
                # Exception messages from network libraries can include credentials/URLs.
                "failure_type": type(exc).__name__,
                "failure_location": f"{Path(traceback.extract_tb(exc.__traceback__)[-1].filename).name}:{traceback.extract_tb(exc.__traceback__)[-1].lineno}",
            })
            if isinstance(exc, HTTPError):
                decision["http_status"] = exc.code
            decision["tool_runs"] = [
                {"tool_call_id": result["tool_call_id"],
                 "log_file": f'runs/{result["tool_call_id"]}/{result["tool_call_id"]}.log',
                 "exit_status": result["exit_status"]}
                for path in sorted((target / "runs").glob("R*/execution.json"))
                for result in [json.loads(path.read_text(encoding="utf-8"))]
            ]
            decision_path.write_text(json.dumps(decision, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps({"execution_complete": False, "failure_type": type(exc).__name__}))
        return 1
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)


def arm_deadline(limitations, started):
    match = re.search(r"不超过\s*(\d+)\s*秒", limitations)
    if not match:
        raise ValueError("Could not determine wall-time limit")
    deadline = started + int(match[1]) - 10
    def expired(signum, frame):
        raise TimeoutError("Case wall-time budget exhausted")
    signal.signal(signal.SIGALRM, expired)
    signal.setitimer(signal.ITIMER_REAL, max(0.001, deadline - time.monotonic()))
    return deadline


def task1_full_insertion(specification):
    # These explicit task statements distinguish preprocessing from insertion;
    # never infer the requested flow from the candidate generated by the model.
    return not re.search(r"不(?:构建扫描链|涉及扫描链的构建)|仅替换[，,、\s]*不插链", specification)


def design_outline(source):
    """Read declarations and hierarchical instances in the supplied gate netlists.

    This small outline is prompt context, not a Verilog semantic parser. Cell
    connectivity and flattened library instances are not sent to the model.
    """
    modules, names, control_bodies = [], set(), {}
    gate_sample_types, gate_sample_kinds = set(), set()
    paths = sorted((source / "netlist").glob("*.v"))
    for path in paths:
        header, module_name, control_name, body = [], None, None, ""
        with path.open(encoding="utf-8") as stream:
            for line in stream:
                match = re.match(r"\s*module\s+(\S+?)(?:\s|\()", line)
                if match:
                    names.add(match[1])
                    module_name, header = match[1], []
                    gate_kind = re.match(r"SNPS_CLOCK_GATE_(HIGH|LOW)", match[1])
                    sample_gate = gate_kind and gate_kind[1] not in gate_sample_kinds
                    if sample_gate:
                        gate_sample_kinds.add(gate_kind[1])
                        gate_sample_types.add(match[1])
                    control_name = match[1] if sample_gate or (not match[1].startswith("SNPS_CLOCK_GATE") and re.search(r"clk|clock|icg|BUFG", match[1], re.I)) else None
                    body = ""
                if control_name is not None:
                    body += line
                    if len(body) > 4096:
                        control_name = None
                    elif re.match(r"\s*endmodule\b", line):
                        control_bodies[control_name] = body
                        control_name = None
                if module_name is not None:
                    header.append(line.strip())
                    if ";" in line:
                        modules.append((module_name, header))
                        module_name = None
    instances = []
    for path in paths:
        module, current_instance = None, None
        with path.open(encoding="utf-8") as stream:
            for number, line in enumerate(stream, 1):
                match = re.match(r"\s*module\s+(\S+?)(?:\s|\()", line)
                if match:
                    module = match[1]
                match = re.match(r"\s*(\S+)\s+(\S+?)\s*\(", line)
                if match and (match[1] in names or re.search(r'(?:clk|clock).*latch', match[2], re.I)):
                    current_instance = {"module": module, "type": match[1], "instance": match[2],
                                        "source": str(path.relative_to(source)), "line": number, "unconnected_pins": []}
                    if match[1] not in names or match[1] in gate_sample_types or (not match[1].startswith("SNPS_CLOCK_GATE") and re.search(r"clk|clock|icg|BUFG", match[1], re.I)):
                        current_instance["connections"] = {}
                    instances.append(current_instance)
                if current_instance is not None:
                    current_instance["unconnected_pins"].extend(re.findall(r"\.(\w+)\s*\(\s*\)", line))
                    if "connections" in current_instance:
                        current_instance["connections"].update((pin, net.strip()) for pin, net in re.findall(r"\.(\w+)\s*\(([^()]*)\)", line))
                    if ";" in line:
                        current_instance = None
    children = {name: [] for name in names}
    for item in instances:
        children[item["module"]].append(item)
    roots = names - {item["type"] for item in instances}
    resolved = []
    pending = [(root, "", ()) for root in sorted(roots)]
    while pending:
        module, prefix, ancestors = pending.pop()
        if module in ancestors:
            raise ValueError("Recursive module hierarchy is unsupported")
        for item in children[module]:
            path = prefix + item["instance"]
            resolved.append({"path": path, "type": item["type"], "unconnected_pins": item["unconnected_pins"]})
            if "connections" in item:
                resolved[-1]["connections"] = item["connections"]
            if item["type"] in control_bodies:
                resolved[-1]["output_pins"] = re.findall(r"(?m)^\s*output\s+(\w+)\s*;", control_bodies[item["type"]])
            if item["type"] in gate_sample_types:
                resolved[-1]["representative_synthesized_clock_gate"] = True
            if item["type"] in children:
                pending.append((item["type"], path + "/", ancestors + (module,)))
    # Synthesized large cores contain tens of thousands of repeated clock-gate
    # wrappers. Keep functional hierarchy and relevant controls, not every copy.
    # Floating hierarchy pins remain visible regardless of module naming.
    if len(resolved) > 2000:
        resolved = [item for item in resolved if item["path"].count("/") < 2 or item["unconnected_pins"] or item["type"] in gate_sample_types
                    or (not item["type"].startswith("SNPS_CLOCK_GATE") and
                        re.search(r"(?:clk|clock).*top|jtag|tap|dft|reset|BUFG", item["type"], re.I))]
    resolved = [item for item in resolved if not item["type"].startswith("SNPS_CLOCK_GATE")
                or item["type"] in gate_sample_types or item["unconnected_pins"]]
    used_types = roots | {item["type"] for item in resolved}
    for index, item in enumerate(resolved):
        item["selector"] = f"[[H{index}]]"
    body_types = gate_sample_types | {item["type"] for item in resolved if item["unconnected_pins"] or item["path"].count("/") < 2}
    return [" ".join(header) if name in roots else control_bodies[name] if name in body_types and name in control_bodies else header[0]
            for name, header in modules if name in used_types], resolved


def generate(prompt, timeout, instructions=None, output_schema=TASK1):
    payload = {
        "model": os.environ["LLM_MODEL"],
        "instructions": instructions or (
            "You are a Scan Insertion engineer. Return only JSON with dofile (string), "
            "requirements (array of {requirement, command}). Every requirement must map to an "
            "exact command substring of dofile. Use supplied tool documentation. Never fabricate "
            "logs, reports, or netlists. Do not modify input files. Do not execute shell commands. "
            "Use $input_dir, $out_res_dir, $out_rpt_dir which are defined by the runner. "
            "Export with literal paths like $out_res_dir/file.v or $out_rpt_dir/file.rpt. "
            "Only generate the task's requested stages; preprocessing tasks must not build chains. "
            "hierarchical_instances provides selector tokens like [[H12]] for actual instances. "
            "Use those tokens in dofile AND requirement commands instead of retyping hierarchy paths, "
            "e.g. add_pseudo_pi {[[H12]]/clk_out}. The runner expands tokens to exact source paths. "
            "Never add ancestors or prepend the top module. "
            "Instance connections map PIN NAME keys to PARENT NET NAME values: append the KEY "
            "to an instance selector, never the connected net value. For .Q(net42), the pin "
            "is [[H12]]/Q, not [[H12]]/net42. Declare pseudo inputs BEFORE defining their clock signals. "
            "A leaf name mentioned by the task is not necessarily a top-level instance. Never silently ignore "
            "a Nothing matched warning for a required object selector. "
            "For full_insertion=true, run exactly one examine_scan_drc, examine_scan_chain, "
            "insert_dft_logic in that order (literal command is insert_dft_logic, never 'full insert_dft_logic'). "
            "If required, a separate -connect_icg_only "
            "preprocessing call is allowed BEFORE those three stages, not after DRC. "
            "Export DRC, scan_chain, scan_cfg, scan_signal, "
            "scan_chain_cell and insertion_info reports for acceptance, plus all requested outputs. "
            "End with exit. Do not define or change the runner's path variables."
            " When previous_run is provided, also return repair with located_object, root_cause "
            "and action strings explaining the correction. Recheck the original task's distinct "
            "object scopes: ICG exclusions and non-scannable FF hierarchies are separate requirements."
        ),
        "input": prompt,
        "reasoning": {"effort": "low" if timeout <= 180 else "medium"},
        "stream": True,
        "store": False,
        "text": {"format": {"type": "json_schema", "name": "scan_response", "strict": True, "schema": output_schema}},
    }
    request = urllib.request.Request(
        os.environ["LLM_BASE_URL"].rstrip("/") + "/responses",
        data=json.dumps(payload).encode(),
        headers={"Authorization": "Bearer " + os.environ["LLM_API_KEY"], "Content-Type": "application/json"},
    )
    completed = None
    request_deadline = time.monotonic() + timeout
    failed_http = []
    for attempt in range(2):
        try:
            with urllib.request.urlopen(request, timeout=max(0.001, request_deadline - time.monotonic())) as response:
                for line in response:
                    if not line.startswith(b"data: ") or line.strip() == b"data: [DONE]":
                        continue
                    event = json.loads(line[6:])
                    if event.get("type") == "response.completed":
                        completed = event["response"]
                    if event.get("type") in {"error", "response.failed"}:
                        raise RuntimeError("Model request failed")
            break
        except HTTPError as exc:
            if attempt or exc.code not in (502, 503, 504) or request_deadline - time.monotonic() <= 30:
                raise
            failed_http.append(exc.code)
    if completed is None:
        raise RuntimeError("Missing response.completed")
    text = "".join(c["text"] for item in completed.get("output", []) for c in item.get("content", []) if c.get("type") == "output_text")
    usage = completed.get("usage")
    if failed_http and usage is not None:
        usage["failed_http_statuses"] = failed_http
    return json.loads(text), usage


def execute(args):
    started = time.monotonic()
    source = Path(args.input).resolve()
    target = Path(args.output).resolve()
    prepare_output(target)
    limitations = (source / "limitations.md").read_text(encoding="utf-8")
    deadline = arm_deadline(limitations, started)
    if (source / "original.dofile").exists():
        from repair_task import repair
        return repair(source, target, started, deadline, generate, design_outline)
    specification = (source / "task_spec.md").read_text(encoding="utf-8")
    full_insertion = bool(task1_full_insertion(specification))
    files = [str(p.relative_to(source)) for p in source.rglob("*") if p.is_file() and p.suffix in {".v", ".lib", ".ctl"}]
    modules, instances = design_outline(source)
    guide = (Path(__file__).parent / "commands.md").read_text(encoding="utf-8")
    # Small supplied component definitions expose custom wrapper pins and CTL
    # interfaces; declarations alone omit the information needed to map them.
    component_sources = {name: (source / name).read_text(encoding="utf-8") for name in files
                         if Path(name).suffix in {".v", ".ctl"} and (source / name).stat().st_size <= 32768}
    prompt = json.dumps({"task_spec": specification, "full_insertion": full_insertion, "limitations": limitations, "files": files, "module_declarations": modules, "hierarchical_instances": instances, "component_sources": component_sources, "tool_guide": guide}, ensure_ascii=False)
    plan, usage = generate(prompt, max(1, deadline - time.monotonic()))
    (target / "model_plan.json").write_text(json.dumps({"plan": plan, "usage": usage}, ensure_ascii=False, indent=2), encoding="utf-8")
    run_dir = target / "runs/R1"
    script = generated_script(source, run_dir, resolve_selectors(plan["dofile"], instances))
    if deadline <= time.monotonic():
        raise TimeoutError("No budget remaining for Scan")
    result = run_scan(script, run_dir, deadline - time.monotonic())
    acceptance, artifacts, _ = inspect_run(run_dir, script, result, full_insertion=full_insertion, task_spec=specification, design_context=instances)
    runs = [result]
    issue_resolutions = []
    changes = []
    run_id = "R1"
    while not acceptance["accepted"] and result["exit_status"] != "aborted" and deadline - time.monotonic() > 30:
        old_id = run_id
        original_script = script
        evidence_path = run_dir / "acceptance.json"
        old_evidence = evidence_path.read_text(encoding="utf-8")
        failed_check = next(key for key, value in acceptance["checks"].items() if value is not True)
        first_error = result["errors"][0] if result["errors"] else f"Acceptance failed: {failed_check}"
        failure_excerpt = f'"{failed_check}": false'
        repair_input = json.loads(prompt)
        repair_input["previous_run"] = {"dofile": plan["dofile"], "errors": result["errors"],
                                        "acceptance": acceptance,
                                        "tool_messages": "\n".join(line for line in artifacts[f"{old_id}.log"].splitlines()
                                                                   if any(tag in line for tag in ("CMD-0034", "WARNING", "ERROR")))[:20000],
                                        "report_excerpts": {name: text[:12000] for name, text in artifacts.items()
                                                            if name.endswith(".rpt") and "CellNo" not in text}}
        plan, repair_usage = generate(json.dumps(repair_input, ensure_ascii=False), deadline - time.monotonic())
        run_id = f"R{len(runs) + 1}"
        (target / f"model_repair_{run_id}.json").write_text(json.dumps({"plan": plan, "usage": repair_usage}, ensure_ascii=False, indent=2), encoding="utf-8")
        run_dir = target / "runs" / run_id
        script = generated_script(source, run_dir, resolve_selectors(plan["dofile"], instances))
        change_id = f"F{len(changes) + 1}"
        changes.append(record_change(target, old_id, run_id, original_script, script, change_id))
        result = run_scan(script, run_dir, max(0.001, deadline - time.monotonic()))
        runs.append(result)
        acceptance, artifacts, _ = inspect_run(run_dir, script, result, full_insertion=full_insertion, task_spec=specification, design_context=instances)
        new_lines = (run_dir / "acceptance.json").read_text(encoding="utf-8").splitlines()
        evidence = [(i, line) for i, line in enumerate(new_lines, 1) if '"accepted": true' in line]
        resolved = acceptance["accepted"]
        repair = {key: resolve_selectors(value, instances) for key, value in plan.get("repair", {}).items()}
        issue_resolutions.append({
            "issue_id": f"I{len(issue_resolutions) + 1}", "phenomenon": first_error,
            "found": {"run_ref": old_id, "source": f"runs/{old_id}/acceptance.json", "locator": f'L{old_evidence[:old_evidence.index(failure_excerpt)].count(chr(10)) + 1}', "excerpt": failure_excerpt},
            "diagnosis": {"summary": "依据实际执行与验收失败记录重新核对任务要求。", "located_object": repair.get("located_object", failed_check), "root_cause": repair.get("root_cause", "模型未返回根因解释；仅记录实际验收失败，不推断根因。")},
            "attempts": [{"fix": {"action": repair.get("action", "模型根据失败反馈生成新候选，变更见关联 diff；未提供修复解释。"), "artifact_ref": [change_id]}, "verify": {"run_ref": run_id, "source": f"runs/{run_id}/acceptance.json", "resolved": resolved, "locator": f"L{evidence[-1][0]}" if resolved else "", "excerpt": evidence[-1][1] if resolved else ""}}],
        })
        (target / "decision_log.json").write_text(json.dumps({
            "case_id": os.environ.get("CASE_ID", source.parent.name), "task": "task1",
            "final_run": None, "summary": "Repair executed; final acceptance pending.",
            "issue_resolutions": issue_resolutions, "file_changes": changes,
        }, ensure_ascii=False, indent=2), encoding="utf-8")
    missing = acceptance["missing_outputs"]
    success = acceptance["accepted"]
    mappings = []
    for requirement in plan["requirements"]:
        command = resolve_selectors(requirement["command"], instances)
        # A requirement can cite several real statements that are not adjacent.
        # Give each an exact source reference rather than inventing a continuous
        # excerpt or rejecting a correct executed script for their grouping.
        commands = [command] if command in script and command else command.splitlines()
        if not commands or any(not item.strip() or item not in script for item in commands):
            raise ValueError("Requirement command is absent from generated dofile")
        for item in commands:
            line = script[:script.index(item)].count("\n") + 1
            mappings.append({"requirement": requirement["requirement"], "dft_config": item, "config_ref": {"source": "final_results/deliverables/final.dofile", "locator": f"L{line}"}})
    if success:
        publish_run(target, run_dir)
    decision = {
        "case_id": os.environ.get("CASE_ID", source.parent.name or source.name), "task": "task1", "final_run": run_id if success else None,
        "summary": "工具执行及支持范围内的任务验收通过；非完整语义证明。" if success else f"执行或任务验收失败；缺少交付物: {missing}",
        "requirement_mapping": mappings if success else [], "issue_resolutions": issue_resolutions,
        "tool_runs": [{"tool_call_id": r["tool_call_id"], "log_file": f'runs/{r["tool_call_id"]}/{r["tool_call_id"]}.log', "exit_status": r["exit_status"]} for r in runs],
        "file_changes": changes,
        "independent_checks": acceptance["checks"],
    }
    (target / "decision_log.json").write_text(json.dumps(decision, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"execution_complete": success, "semantic_acceptance": "supported_report_checks" if full_insertion else "not_yet_verified", "elapsed": round(time.monotonic() - started, 2)}))
    return 0 if success else 1


if __name__ == "__main__":
    raise SystemExit(main())
