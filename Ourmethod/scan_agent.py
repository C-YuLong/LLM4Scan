def prepare_output(target):
    target.mkdir(parents=True, exist_ok=True)
    if any(target.iterdir()):
        raise ValueError("Output directory must be empty; previous runs are preserved")
    # Persist a truthful decision before the first network/tool operation.
    (target / "decision_log.json").write_text(json.dumps({
        "case_id": os.environ.get("CASE_ID", ""), "final_run": None,
        "summary": "Execution started; acceptance pending.",
        "tool_runs": [], "file_changes": [], "issue_resolutions": [],
    }, indent=2), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("-input", "--input", required=True)
    parser.add_argument("-output", "--output", help="Optional exact output directory")
    parser.add_argument("--output-root", default=os.environ.get("AGENT_OUTPUT_ROOT", "/output"),
                        help="Parent for automatically named local runs (default: /output)")
    parser.add_argument("--config", help="TOML component/model configuration")
    parser.add_argument("--generator", help="Override configured generator selection")
    parser.add_argument("--verifier", help="Override configured verifier selection")
    parser.add_argument("--verification-mode", choices=("gate", "shadow"))
    args = parser.parse_args()
    if args.output is None:
        args.output = str(telemetry.auto_output(args.input, args.output_root))
    target = Path(args.output).resolve()
    # Check before entering the failure handler: never rewrite an old run.
    if target.exists() and any(target.iterdir()):
        raise ValueError("Output directory must be empty; previous runs are preserved")
    exit_code = 1
    try:
        exit_code = execute(args)
        return exit_code
    except Exception as exc:
        signal.setitimer(signal.ITIMER_REAL, 0)
        decision_path = target / "decision_log.json"
        if decision_path.exists():
            decision = json.loads(decision_path.read_text(encoding="utf-8"))
            decision.update({
                "task": "task2" if (Path(args.input) / "original.dofile").exists() else "task1",
                "final_run": None, "summary": "Execution failed before final acceptance.",
                # Exception messages from network libraries can include credentials/URLs.
                "failure_type": type(exc).__name__,
                "failure_location": f"{Path(traceback.extract_tb(exc.__traceback__)[-1].filename).name}:{traceback.extract_tb(exc.__traceback__)[-1].lineno}",
            })
            if isinstance(exc, HTTPError):
                decision["http_status"] = exc.code
            decision["tool_runs"] = [
                {"tool_call_id": result["tool_call_id"],
                 "log_file": f'runs/{result["tool_call_id"]}/{result["tool_call_id"]}.log',
                 "exit_status": result["exit_status"]}
                for path in sorted((target / "runs").glob("R*/execution.json"))
                for result in [json.loads(path.read_text(encoding="utf-8"))]
            ]
            decision_path.write_text(json.dumps(decision, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps({"execution_complete": False, "failure_type": type(exc).__name__}))
        return 1
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        telemetry.finish(exit_code)


def arm_deadline(limitations, started):
    match = re.search(r"不超过\s*(\d+)\s*秒", limitations)
    if not match:
        raise ValueError("Could not determine wall-time limit")
    deadline = started + int(match[1]) - 10
    def expired(signum, frame):
        raise TimeoutError("Case wall-time budget exhausted")
    signal.signal(signal.SIGALRM, expired)
    signal.setitimer(signal.ITIMER_REAL, max(0.001, deadline - time.monotonic()))
    return deadline


def task1_full_insertion(specification):
    # These explicit task statements distinguish preprocessing from insertion;
    # never infer the requested flow from the candidate generated by the model.
    return not re.search(r"不(?:构建扫描链|涉及扫描链的构建)|仅替换[，,、\s]*不插链", specification)


def execute(args):
    started = time.monotonic()
    source = Path(args.input).resolve()
    target = Path(args.output).resolve()
    from components import from_args
    try:
        runtime = from_args(args, source)
    except ValueError as exc:
        # Startup validation messages contain config keys, never resolved secrets.
        print(json.dumps({"configuration_error": str(exc)}, ensure_ascii=False))
        raise
    generate_fn = generate if runtime is None else runtime.generator
    prepare_output(target)
    if runtime is not None:
        (target / "config_snapshot.json").write_text(json.dumps(runtime.config.snapshot(), ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    telemetry.start(target)
    with telemetry.phase("input", "读取任务时间限制并设置总预算"):
        limitations = (source / "limitations.md").read_text(encoding="utf-8")
        deadline = arm_deadline(limitations, started)
        telemetry.set_deadline(deadline)
    if (source / "original.dofile").exists():
        from repair_task import repair
        return repair(source, target, started, deadline, generate_fn, design_outline)
    with telemetry.phase("input", "读取 Task 1 任务与输入文件清单"):
        specification = (source / "task_spec.md").read_text(encoding="utf-8")
        full_insertion = bool(task1_full_insertion(specification))
        files = [str(p.relative_to(source)) for p in source.rglob("*") if p.is_file() and p.suffix in {".v", ".lib", ".ctl"}]
    modules, instances = design_outline(source)
    with telemetry.phase("context", "整理 Task 1 模型上下文"):
        guide = (Path(__file__).parent / "commands.md").read_text(encoding="utf-8")
        prompt = build_task1_prompt(source, specification, full_insertion, limitations, files, modules, instances, guide)
    def inspect_candidate(run_dir, script, result):
        options = dict(full_insertion=full_insertion, task_spec=specification, design_context=instances)
        if runtime is None:
            return inspect_run(run_dir, script, result, **options)
        return runtime.inspect(inspect_run, source, run_dir, script, result, deadline, **options)
    plan, usage = generate_fn(prompt, max(1, deadline - time.monotonic()))
    (target / "model_plan.json").write_text(json.dumps({"plan": plan, "usage": usage}, ensure_ascii=False, indent=2), encoding="utf-8")
    run_dir = target / "runs/R1"
    script = generated_script(source, run_dir, resolve_selectors(plan["dofile"], instances))
    if deadline <= time.monotonic():
        raise TimeoutError("No budget remaining for Scan")
    from stage_artifacts import resolve_stage_declarations
    stages=resolve_stage_declarations(plan.get("stages"),lambda text:resolve_selectors(text,instances))
    result = run_scan(script, run_dir, deadline - time.monotonic(),stages=stages,source=source)
    acceptance, artifacts, _ = inspect_candidate(run_dir, script, result)
    runs = [result]
    issue_resolutions = []
    changes = []
    run_id = "R1"
    while not acceptance["accepted"] and acceptance.get("verification_status") != "UNKNOWN" and result["exit_status"] != "aborted" and deadline - time.monotonic() > 30:
        old_id = run_id
        original_script = script
        evidence_source = acceptance.get("_evidence_source", "acceptance.json")
        evidence_path = run_dir / evidence_source
        old_evidence = evidence_path.read_text(encoding="utf-8")
        failed_check = next(key for key, value in acceptance["checks"].items() if value is not True)
        first_error = result["errors"][0] if result["errors"] else f"Acceptance failed: {failed_check}"
        failure_excerpt = f'"{failed_check}": false'
        plan, repair_usage = revise_task1(prompt, plan, result, acceptance, artifacts, old_id, deadline, generate_fn)
        run_id = f"R{len(runs) + 1}"
        (target / f"model_repair_{run_id}.json").write_text(json.dumps({"plan": plan, "usage": repair_usage}, ensure_ascii=False, indent=2), encoding="utf-8")
        run_dir = target / "runs" / run_id
        script = generated_script(source, run_dir, resolve_selectors(plan["dofile"], instances))
        change_id = f"F{len(changes) + 1}"
        changes.append(record_change(target, old_id, run_id, original_script, script, change_id))
        stages=resolve_stage_declarations(plan.get("stages"),lambda text:resolve_selectors(text,instances))
        result = run_scan(script, run_dir, max(0.001, deadline - time.monotonic()),stages=stages,source=source)
        runs.append(result)
        acceptance, artifacts, _ = inspect_candidate(run_dir, script, result)
        new_evidence_source = acceptance.get("_evidence_source", "acceptance.json")
        new_lines = (run_dir / new_evidence_source).read_text(encoding="utf-8").splitlines()
        evidence = [(i, line) for i, line in enumerate(new_lines, 1) if '"accepted": true' in line]
        resolved = acceptance["accepted"]
        repair = {key: resolve_selectors(value, instances) for key, value in plan.get("repair", {}).items()}
        issue_resolutions.append({
            "issue_id": f"I{len(issue_resolutions) + 1}", "phenomenon": first_error,
            "found": {"run_ref": old_id, "source": f"runs/{old_id}/{evidence_source}", "locator": f'L{old_evidence[:old_evidence.index(failure_excerpt)].count(chr(10)) + 1}', "excerpt": failure_excerpt},
            "diagnosis": {"summary": "依据实际执行与验收失败记录重新核对任务要求。", "located_object": repair.get("located_object", failed_check), "root_cause": repair.get("root_cause", "模型未返回根因解释；仅记录实际验收失败，不推断根因。")},
            "attempts": [{"fix": {"action": repair.get("action", "模型根据失败反馈生成新候选，变更见关联 diff；未提供修复解释。"), "artifact_ref": [change_id]}, "verify": {"run_ref": run_id, "source": f"runs/{run_id}/{new_evidence_source}", "resolved": resolved, "locator": f"L{evidence[-1][0]}" if resolved else "", "excerpt": evidence[-1][1] if resolved else ""}}],
        })
        (target / "decision_log.json").write_text(json.dumps({
            "case_id": os.environ.get("CASE_ID", source.parent.name), "task": "task1",
            "final_run": None, "summary": "Repair executed; final acceptance pending.",
            "issue_resolutions": issue_resolutions, "file_changes": changes,
        }, ensure_ascii=False, indent=2), encoding="utf-8")
    missing = acceptance["missing_outputs"]
    success = acceptance["accepted"]
    mappings = []
    for requirement in plan["requirements"]:
        command = resolve_selectors(requirement["command"], instances)
        # A requirement can cite several real statements that are not adjacent.
        # Give each an exact source reference rather than inventing a continuous
        # excerpt or rejecting a correct executed script for their grouping.
        commands = [command] if command in script and command else command.splitlines()
        if not commands or any(not item.strip() or item not in script for item in commands):
            raise ValueError("Requirement command is absent from generated dofile")
        for item in commands:
            line = script[:script.index(item)].count("\n") + 1
            mappings.append({"requirement": requirement["requirement"], "dft_config": item, "config_ref": {"source": "final_results/deliverables/final.dofile", "locator": f"L{line}"}})
    if success:
        publish_run(target, run_dir)
    decision = {
        "case_id": os.environ.get("CASE_ID", source.parent.name or source.name), "task": "task1", "final_run": run_id if success else None,
        "summary": "工具执行及支持范围内的任务验收通过；非完整语义证明。" if success else f"执行或任务验收失败；缺少交付物: {missing}",
        "requirement_mapping": mappings if success else [], "issue_resolutions": issue_resolutions,
        "tool_runs": [{"tool_call_id": r["tool_call_id"], "log_file": f'runs/{r["tool_call_id"]}/{r["tool_call_id"]}.log', "exit_status": r["exit_status"]} for r in runs],
        "file_changes": changes,
        "independent_checks": acceptance["checks"],
    }
    semantic_acceptance = "supported_report_checks" if full_insertion else "not_yet_verified"
    if runtime is not None and runtime.verifier_client is not None:
        decision.update(verifier=runtime.config.verifier["backend"], verification_mode=runtime.config.pipeline["verification_mode"])
        if runtime.config.pipeline["verification_mode"] == "gate":
            decision["verification_status"] = acceptance["verification_status"]
            decision["summary"] = acceptance["check_details"]["summary"]
            semantic_acceptance = runtime.config.verifier["backend"]+"_" + acceptance["verification_status"].lower()
    (target / "decision_log.json").write_text(json.dumps(decision, ensure_ascii=False, indent=2), encoding="utf-8")
    if success and runtime is not None and not runtime.check_publication(target, run_dir):
        success = False
        decision.update(final_run=None, summary="Published files did not match verified candidate")
        (target / "decision_log.json").write_text(json.dumps(decision, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({"execution_complete": success, "semantic_acceptance": semantic_acceptance, "elapsed": round(time.monotonic() - started, 2)}))
    return 0 if success else 1


if __name__ == "__main__":
    raise SystemExit(main())
